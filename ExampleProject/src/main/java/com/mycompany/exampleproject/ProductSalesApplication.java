    private void loadProductData() {

    int intTotalSales = objProductSales.GetTotalSales();
    int intAverageSales = (int) Math.round(objProductSales.GetAverageSales());
    int intSalesOverLimit = objProductSales.GetSalesOverLimit();
    int intSalesUnderLimit = objProductSales.GetSalesUnderLimit();
    int intYearsProcessed = objProductSales.GetProductsProcessed();

    txtProductData.setText(
            "Total Sales: " + intTotalSales
            + "\nAverage Sales: " + intAverageSales
            + "\nSales Over Limit: " + intSalesOverLimit
            + "\nSales Under Limit: " + intSalesUnderLimit
    );

    lblYearsProcessed.setText("Years Processed: " + intYearsProcessed);
}

